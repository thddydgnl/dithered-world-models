#!/bin/bash
# Build the arXiv version (v2) of paper A from paper/tmlr/main.tex (the source of record), as for paper B:
#   * a de-anonymized copy of main.tex: [preprint] option, \arxivtrue, the commented author block switched on,
#     full-line comments removed, \pdfoutput=1 for arXiv;
#   * its PDF, compiled here with tectonic (arXiv compiles with pdflatex; the source uses no engine-specific code);
#   * the source package to upload (main.tex, main.bbl, numbers.tex, figures, tables, style files).
# Output: paper/tmlr/arxiv/ (add /paper/tmlr/arxiv/ to .gitignore before the first run), then, with --archive, a copy
#         in ~/Documents/research/papers/Dithered_Low-Bit_World_Models/arXiv/ with a line in its 원고_갱신기록.txt.
# PLAN_tmlr.md 4.9: arXiv v2 goes up after the user approves the revised manuscript. Refuses while \todo markers remain.
# Usage: bash paper/tmlr/build/make_arxiv.sh [--archive] ["short note for the log"]
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
TMLR="$(cd "$HERE/.." && pwd)"
OUT="$TMLR/arxiv"
SRC="$OUT/src"
ARCHIVE=0
if [ "${1:-}" = "--archive" ]; then ARCHIVE=1; shift; fi
NOTE="${1:-}"
PDFNAME="Dithered_Low-Bit_World_Models_arXiv_v2_원고.pdf"
TARNAME="Dithered_Low-Bit_World_Models_arXiv_v2_source.tar.gz"
DEST="$HOME/Documents/research/papers/Dithered_Low-Bit_World_Models/arXiv"
PDF_SOURCES=(main.tex numbers.tex refs.bib math_commands.tex tmlr.sty tmlr.bst fancyhdr.sty figures tables
             build/make_numbers.py build/make_figs.py build/make_tables.py build/make_arxiv.sh)

if grep -q '\\todo{' "$TMLR/main.tex"; then
  echo "main.tex still has \\todo markers; the arXiv version is built from the finished manuscript only."; exit 1
fi

# 1. the arXiv copy of main.tex -------------------------------------------------------------------------------------
rm -rf "$SRC"                      # generated by this script only
mkdir -p "$SRC/figures" "$SRC/tables"
python3 -I - "$TMLR/main.tex" "$SRC/main.tex" <<'PY'
import re, sys
src, dst = sys.argv[1], sys.argv[2]
s = open(src, encoding="utf-8").read()
# switch the author block on: uncomment the lines between the two markers, then drop the markers
block = re.search(r"% BEGIN-AUTHOR-BLOCK[^\n]*\n(.*?)% END-AUTHOR-BLOCK[^\n]*\n", s, re.S)
assert block, "author block markers not found"
author = "\n".join(re.sub(r"^%\s?", "", l) for l in block.group(1).rstrip("\n").split("\n")) + "\n"
s = s[:block.start()] + author + s[block.end():]
lines = s.split("\n")
kept = [l for l in lines if not re.match(r"^\s*%", l)]          # the source's working notes are not for arXiv
s = "\n".join(kept).lstrip("\n")
def rep(old, new):
    global s
    assert s.count(old) == 1, (old, s.count(old))
    s = s.replace(old, new)
rep("\\usepackage{tmlr}", "\\usepackage[preprint]{tmlr}")           # shows the author block, empty running head
rep("\\newif\\ifarxiv\\arxivfalse", "\\newif\\ifarxiv\\arxivtrue")  # Reproducibility -> public repository
rep("pdfauthor={}", "pdfauthor={Yong Hwi Song, Keon Myung Lee}")
header = ("\\pdfoutput=1\n"
          "% arXiv version, generated by paper/tmlr/build/make_arxiv.sh from main.tex (the source of record).\n"
          "% Line 1 tells arXiv to use pdflatex; delete it to compile this file with XeLaTeX or tectonic.\n")
s = header + s
assert "\\arxivfalse" not in s and "\\author{" in s
open(dst, "w", encoding="utf-8").write(s)
print(f"wrote {dst}: {len(kept)} lines ({len(lines)-len(kept)} comment lines dropped)")
PY
cp "$TMLR"/figures/*.pdf "$SRC/figures/"
cp "$TMLR"/tables/*.tex "$SRC/tables/"
cp "$TMLR"/refs.bib "$TMLR"/numbers.tex "$TMLR"/tmlr.sty "$TMLR"/tmlr.bst "$TMLR"/fancyhdr.sty "$TMLR"/math_commands.tex "$SRC/"

# 2. compile; keep main.bbl (arXiv does not run bibtex) ---------------------------------------------------------------
( cd "$SRC" && sed '1s/^\\pdfoutput=1$/\\relax/' main.tex > main_local.tex && head -1 main_local.tex | grep -q '^\\relax$' \
  && tectonic -X compile --keep-intermediates --keep-logs main_local.tex \
  && mv main_local.pdf main.pdf && mv main_local.bbl main.bbl && mv main_local.log main.log && rm -f main_local.* )
[ -f "$SRC/main.bbl" ] || { echo "no main.bbl produced"; exit 1; }
mv "$SRC/main.pdf" "$OUT/$PDFNAME"
mv "$SRC/main.log" "$OUT/main.log"
rm -f "$SRC"/main.aux "$SRC"/main.blg "$SRC"/main.out "$SRC"/main.xdv "$SRC"/main.fls "$SRC"/main.toc
if grep -q "LaTeX Warning: There were undefined references\|LaTeX Warning: Label(s) may have changed" "$OUT/main.log"; then
  echo "WARNING: unresolved references in the arXiv build (see $OUT/main.log)"; exit 1
fi

# 3. the upload package --------------------------------------------------------------------------------------------------
rm -f "$OUT/$TARNAME"
( cd "$SRC" && COPYFILE_DISABLE=1 tar czf "$OUT/$TARNAME" --exclude .DS_Store . )

# 4. checks on the PDF ---------------------------------------------------------------------------------------------------
PAGES="$(python3 -I - "$OUT/$PDFNAME" <<'PY'
import sys
import pymupdf
doc = pymupdf.open(sys.argv[1])
first = doc[0].get_text()
text = "".join(p.get_text() for p in doc)
squash = lambda t: "".join(t.split())
for must in ["Yong Hwi Song", "Keon Myung Lee", "Chungbuk National University"]:
    assert squash(must) in squash(first), f"missing on page 1: {must}"
for bad in ["Anonymous authors", "Under review as submission", "Paper under double-blind review", "anonymized supplementary"]:
    assert squash(bad) not in squash(text), f"found in arXiv PDF: {bad}"
assert "github.com/thddydgnl/dithered-world-models" in squash(text), "repository URL missing"
print(len(doc))
PY
)"
echo "arXiv PDF: $OUT/$PDFNAME ($PAGES pages); package: $OUT/$TARNAME ($(du -h "$OUT/$TARNAME" | cut -f1))"
tar tzf "$OUT/$TARNAME" | sed 's#^\./##' | grep -v '/$' | sort | sed 's/^/   /'

# 5. copy into the paper archive and log (only with --archive) ------------------------------------------------------------
[ "$ARCHIVE" -eq 1 ] || { echo "not copied to the archive (run with --archive)"; exit 0; }
[ -d "$DEST" ] || { echo "missing $DEST"; exit 1; }
cp "$OUT/$PDFNAME" "$DEST/$PDFNAME"
cp "$OUT/$TARNAME" "$DEST/$TARNAME"
REV="$(git -C "$TMLR" rev-parse --short HEAD 2>/dev/null || echo unknown)"
if [ -n "$(git -C "$TMLR" status --porcelain -- "${PDF_SOURCES[@]}" 2>/dev/null)" ]; then REV="$REV+uncommitted"; fi
LOG="$DEST/원고_갱신기록.txt"
printf '%s\t%s\t%s\t%s\n' "$(date '+%Y-%m-%d %H:%M')" "$REV" "$PAGES" "TMLR source (v2): $NOTE" >> "$LOG"
echo "copied to $DEST ($REV)"

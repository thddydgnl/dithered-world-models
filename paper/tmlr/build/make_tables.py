def csvrows(rel):
    return list(csv.DictReader(open(os.path.join(A, rel))))


def pts(x, nd=0, sign=True):
    """A fraction as points (success) or % (DMC return)."""
    return mn.num(100 * float(x), nd, sign)


def dci(d, ci, nd=0):
    lo, hi = ci if isinstance(ci, (list, tuple)) else mn.ci_str(ci)
    return mn.pci(float(d), lo, hi, nd, 100)



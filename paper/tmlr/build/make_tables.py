def write(name, rows):
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, name)
    with open(path, "w") as fh:
        fh.write("% generated by build/make_tables.py -- do not edit\n")
        fh.write("\n".join(rows) + "\n")
    print("wrote", os.path.relpath(path, TMLR))


def load(rel):
    with open(os.path.join(A, rel)) as fh:
        return json.load(fh)


def main():
    td = load("tmlr_ext/TD_tdmpc2/results/analysis/td_summary.json")
    dw = load("tmlr_ext/DW_dinowm/results/analysis/analysis_dw.json")
    j14 = load("tmlr_ext/MT_317m/results/analysis/e14_judgement.json")
    e14 = list(csv.DictReader(open(os.path.join(A, "tmlr_ext/MT_317m/results/analysis/e14_eval.csv"))))
    c = td["E11"]["cells"]
    units = td["E11"]["units"]
    wall = [x for x in dw["E11"]["cells"] if x["task"] == "wall"][0]
    # [post hoc] DINO-WM PushT 3-bit E11 cell on the new split (deviation D4)
    pu3 = load("tmlr_ext/DW_dinowm/results/analysis_posthoc/posthoc_pusht3.json")["cell"]
    fix14 = j14["descriptive"]["fixes_red_ge_half_among_damaged"]
    n14 = j14["P1"]["n_damaged"]

    # ---- Table 3 (Sec. 4.1): mean damage over damaged cells, by variant, group and seed set
    by = {}
    for r in csv.DictReader(open(os.path.join(A, "main/results/E1_tdmpc2/e1_tdmpc2_cells.csv"))):
        by.setdefault((r["task"], int(r["k"]), r["family"]), {})[r["variant"]] = r
    aff = {k: v for k, v in by.items() if v["det"]["confirmatory"] == "True" and v["det"]["holm_real"] == "True"}

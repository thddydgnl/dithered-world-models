    rows.append((f"PushT (DINO-WM, post hoc) & 3 & {mn.pci(pv['det']['D'], *pv['det']['D_ci'], 0, 100)} & {pu3['class']} & "
                 f"{mn.pci(pu3['d_bias']['diff'], *pu3['d_bias']['ci'], 0, 100)} & "
                 f"{mn.pci(pu3['d_pers']['diff'], *pu3['d_pers']['ci'], 0, 100)} \\\\",
                 f"PushT (DINO-WM, post hoc) & 3 & {reds} \\\\"))
    # review C2: two narrower tables instead of one \resizebox'ed table
    write("tabI_e11_cells.tex", [a for a, b in rows])
    write("tabI_e11_red.tex", [b for a, b in rows])

    # ---- Appendix I: k* per range and rounding (E12)

    # ---- Table 4 (Sec. 5.2): cells repaired (red >= 0.5) per variant and family
    rows = []
    for v in E11_VARS:
        name = r"\shep{} / \shplan" if v == "shep" else VAR_TEX[v]
        mw = f"{units['mw']['n_fix'][v]}/{units['mw']['n_damaged']}"
        dmc = f"{units['dmc']['n_fix'][v]}/{units['dmc']['n_damaged']}"
        big = f"{len(fix14[v])}/{n14}" if v in fix14 else "--"

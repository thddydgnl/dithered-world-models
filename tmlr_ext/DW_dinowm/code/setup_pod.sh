#!/bin/bash
# DINO-WM pod setup of the dw group (paper A TMLR extension, DESIGN_tmlr.md 0.2). Idempotent; prints SETUP_DW_DONE.
# usage: bash /workspace/atm/code/setup_pod.sh <tasks>     e.g. wall,pointmaze | pusht | pointmaze
# Code must already be in /workspace/atm/code (pushed from the Mac). Checkpoints and data come from the DINO-WM OSF
# project (view-only key as in the pilots' setup13.sh); only the needed members are unpacked, each download in its
# own directory. Software as on the E1 server (results/E0_dinowm/env/pip_freeze*.txt): torch 2.4.1+cu124, numpy
# 1.26.4, gym 0.23.1, hydra-core 1.3.2, pymunk 6.2.1, dino_wm 0a9492f, DINOv2 ViT-S/14; PointMaze: MuJoCo 2.1.0 +
# mujoco-py 2.1.2.14 (CPU/OSMesa builder) + d4rl@89141a6 (B E7 setup_pod_e7.sh).
set -u
TASKS=$1
ATM=/workspace/atm; B=$ATM/big; LOGS=$ATM/logs; CODE=$ATM/code; ENVD=$ATM/out/env
mkdir -p $ATM/out/calib $ATM/out/state $ENVD $LOGS $B/data/dinowm $B/ds $B/pairs $B/envs $B/torch $B/hf $B/dl
echo "$TASKS" > $ATM/TASKS
PM=0; case ",$TASKS," in *,pointmaze,*) PM=1 ;; esac
echo $PM > $ATM/WITH_PM
export DEBIAN_FRONTEND=noninteractive
PKG="rsync unzip git curl aria2 libgl1 libglib2.0-0"
[ $PM = 1 ] && PKG="$PKG build-essential libosmesa6-dev libgl1-mesa-dev libglew-dev libglfw3 patchelf"
(apt-get update -qq && apt-get install -y -qq $PKG) > $LOGS/apt.log 2>&1 && echo APT_OK || echo APT_FAIL
VO="view_only=a56a296ce3b24cceaf408383a175ce28"
dl() {   # dl <osf id> <dir> <zip> <unzip args...>: download into its own dir, unzip members, delete the zip
  local id=$1 dir=$2 zip=$3; shift 3
  mkdir -p $dir
  if [ ! -f $dir/.done ]; then
    # multi-connection download (OSF answers range requests; single connections ran at ~175 KB/s on some hosts)
    # aria2c resumes from its control file (.aria2) when rerun; a first run that ends with segments missing is
    # retried twice (seen on dw.1, 2026-11-21)
    (cd $dir && { if command -v aria2c > /dev/null; then
        for a in 1 2 3; do aria2c -c -x16 -s16 -k4M --file-allocation=none --max-tries=10 --retry-wait=3 \
          --summary-interval=0 -o $zip "https://osf.io/download/$id/?$VO" >> aria2_$zip.log 2>&1 && break; done;
      else curl -sSL --retry 5 -o $zip "https://osf.io/download/$id/?$VO"; fi; } \
      && unzip -q -o $zip "$@" && rm -f $zip && touch .done && echo "DL_OK $zip") || echo "DL_FAIL $zip"
  else
    echo "DL_SKIP $zip"
  fi
}
MODELS=()
for t in ${TASKS//,/ }; do
  case $t in pusht) MODELS+=('outputs/pusht/*') ;; wall) MODELS+=('outputs/wall_single/*') ;;
             pointmaze) MODELS+=('outputs/point_maze/*') ;; esac
done
(dl xvzs4 $B/dl/ckpt outputs.zip "${MODELS[@]}") > $LOGS/dl_ckpt.log 2>&1 &
case ",$TASKS," in *,pusht,*) (dl k2d8w $B/dl/pusht pusht_noise.zip -x '*/obses/*') > $LOGS/dl_pusht.log 2>&1 & ;; esac
case ",$TASKS," in *,wall,*) (dl 49rnx $B/dl/wall wall_single.zip 'wall_single/*.pth' -x 'wall_single/obses/*' && \
  mkdir -p $B/dl/wall/wall_single/obses) > $LOGS/dl_wall.log 2>&1 & ;; esac
case ",$TASKS," in *,pointmaze,*) (dl vr5gy $B/dl/pm point_maze.zip 'point_maze/*.pth' -x 'point_maze/obses/*' && \
  mkdir -p $B/dl/pm/point_maze/obses) > $LOGS/dl_pm.log 2>&1 & ;; esac
# python env (uv venv, pinned as on the E1 server)
command -v uv > /dev/null || pip install -q uv > $LOGS/uv.log 2>&1
V=$B/envs/dw
[ -x $V/bin/python ] || uv venv -q --python 3.11 $V
uv pip install -q --python $V/bin/python torch==2.4.1 torchvision==0.19.1 --index-url https://download.pytorch.org/whl/cu124 \
  > $LOGS/pip_torch.log 2>&1 && echo TORCH_OK || echo TORCH_FAIL
uv pip install -q --python $V/bin/python -r $CODE/requirements_dw.txt > $LOGS/pip.log 2>&1 && echo PKGS_OK || echo PKGS_FAIL
if [ $PM = 1 ]; then
  uv pip install -q --python $V/bin/python -r $CODE/requirements_pm.txt >> $LOGS/pip.log 2>&1 && echo PM_PKGS_OK || echo PM_PKGS_FAIL
  MJ=$B/envs/mujoco210
  if [ ! -f $MJ/bin/libmujoco210.so ]; then
    curl -sSL --retry 3 -o $B/dl/mj.tgz https://github.com/google-deepmind/mujoco/releases/download/2.1.0/mujoco210-linux-x86_64.tar.gz \
      && tar -xzf $B/dl/mj.tgz -C $B/envs && rm -f $B/dl/mj.tgz
  fi
  ls $MJ/bin/libmujoco210.so > /dev/null && echo MUJOCO210_OK || echo MUJOCO210_FAIL
  export MUJOCO_PY_MUJOCO_PATH=$MJ MUJOCO_PY_FORCE_CPU=1 LD_LIBRARY_PATH=$MJ/bin:${LD_LIBRARY_PATH:-} PATH=$V/bin:$PATH
  uv pip install -q --python $V/bin/python --no-build-isolation "mujoco-py==2.1.2.14" >> $LOGS/pip.log 2>&1 && echo MJPY_PIP_OK || echo MJPY_PIP_FAIL
  uv pip install -q --python $V/bin/python --no-deps "d4rl @ git+https://github.com/Farama-Foundation/D4RL.git@89141a689b0353b0dac3da5cba60da4b1b16254d" \
    >> $LOGS/pip.log 2>&1 && echo D4RL_PIP_OK || echo D4RL_PIP_FAIL
  # the wheel ships a cymj.c generated by Cython 0.29.24 (includes longintrepr.h, absent in Python 3.11): make the
  # builder re-cythonize cymj.pyx with the pinned Cython 0.29.37 (seen on dw.3, 2026-11-21)
  SPM=$V/lib/python3.11/site-packages/mujoco_py
  grep -q "Generated by Cython 0.29.37" $SPM/cymj.c 2>/dev/null || { touch $SPM/cymj.pyx; rm -rf $SPM/generated/_pyxbld_*; }
  $V/bin/python -c "import mujoco_py; print('MUJOCO_PY_OK')" > $LOGS/mujoco_build.log 2>&1 && echo MUJOCO_PY_OK || { echo MUJOCO_PY_FAIL; tail -5 $LOGS/mujoco_build.log; }
fi
# dino_wm at the E1 commit
[ -d $B/dino_wm/.git ] || git clone -q https://github.com/gaoyuezhou/dino_wm.git $B/dino_wm
(cd $B/dino_wm && git checkout -q 0a9492fa12044b852ae9e001cc74604b79c8bb0c && git log -1 --format='%H %cd') > $ENVD/dino_wm_commit.txt
# DINOv2 ViT-S/14 (torch hub cache)
TORCH_HOME=$B/torch $V/bin/python -c "import torch; torch.hub.load('facebookresearch/dinov2', 'dinov2_vits14'); print('DINOV2_OK')" \
  > $LOGS/hub.log 2>&1 && echo DINOV2_OK || echo DINOV2_FAIL
wait
cat $LOGS/dl_*.log
mkdir -p $B/data/dinowm/outputs
for m in pusht wall_single point_maze; do
  [ -d $B/dl/ckpt/outputs/$m ] && ln -sfn $B/dl/ckpt/outputs/$m $B/data/dinowm/outputs/$m
done
[ -d $B/dl/pusht/pusht_noise ] && ln -sfn $B/dl/pusht/pusht_noise $B/ds/pusht_noise
[ -d $B/dl/wall/wall_single ] && ln -sfn $B/dl/wall/wall_single $B/ds/wall_single
[ -d $B/dl/pm/point_maze ] && ln -sfn $B/dl/pm/point_maze $B/ds/point_maze
cp -n $CODE/inputs/pairs_pusht_eval6.json $B/pairs/ 2>/dev/null
cp -n $CODE/inputs/ranges_main_*.json $ATM/out/calib/ 2>/dev/null
# hashes (checkpoints, hydra configs, dataset metadata) and versions
(cd $B/data/dinowm && sha256sum outputs/*/checkpoints/model_latest.pth outputs/*/hydra.yaml 2>/dev/null) > $ENVD/sha256_ckpt.txt
(cd $B/ds && find -L . -maxdepth 2 \( -name '*.pth' -o -name '*.pkl' \) | sort | xargs -r sha256sum) > $ENVD/sha256_data.txt 2>/dev/null
uv pip freeze --python $V/bin/python > $ENVD/pip_freeze.txt
$V/bin/python - << 'PYEOF' > $ENVD/versions.txt 2>&1
import sys, torch, numpy, gym, pymunk, hydra, scipy
print('python', sys.version.split()[0]); print('torch', torch.__version__, 'cuda', torch.version.cuda, 'cudnn', torch.backends.cudnn.version())
print('numpy', numpy.__version__, 'gym', gym.__version__, 'pymunk', pymunk.version, 'hydra', hydra.__version__, 'scipy', scipy.__version__)
print('gpu', torch.cuda.get_device_name(0), 'driver cuda ok', torch.cuda.is_available())
PYEOF
nvidia-smi --query-gpu=name,memory.total,driver_version --format=csv,noheader >> $ENVD/versions.txt
echo "nproc $(nproc)" >> $ENVD/versions.txt; free -g | head -2 >> $ENVD/versions.txt; df -h /workspace | tail -1 >> $ENVD/versions.txt
cat $ENVD/versions.txt $ENVD/sha256_ckpt.txt
echo SETUP_DW_DONE
